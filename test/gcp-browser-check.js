import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { mkdir } from 'node:fs/promises';
import { createServer } from '../server.js';
import { browserGCP } from './gcp-browser-fixture.js';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const server = createServer(undefined, browserGCP, { pollInterval: 10, maxPolls: 2 });
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const origin = 'http://127.0.0.1:' + server.address().port;
let browser;
try {
  browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const checked = async selector => page.locator(selector).waitFor({ state: 'visible' });
  await page.goto(origin + '/gcp');
  await page.locator('#connectButton').click();
  await page.locator('#projectId').fill('demo-project');
  await page.locator('#projectButton').click();
  await page.locator('#buckets button').first().click();
  await checked('#drop');
  await page.locator('#more').click();
  await page.getByText('page-two.txt', { exact: true }).waitFor();
  await page.locator('#newFolder').click();
  await page.locator('#folderName').fill('new folder');
  await page.locator('#confirmModal').click();
  await page.locator('#modal').waitFor({ state: 'hidden' });
  await page.locator('#objects tr').filter({ hasText: 'assets/' }).locator('input[type=checkbox]').check();
  await page.locator('#copy').click();
  await page.locator('#targetBucket').fill('target-bucket');
  await page.locator('#targetPrefix').fill('copy/');
  assert.equal(await page.locator('input[name=permission]:checked').count(), 0);
  await page.locator('input[name=permission][value=inherit]').check();
  await page.locator('#confirmModal').click();
  await page.locator('#modal').waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.querySelector('#tasks')?.textContent.includes('失败'));
  await page.locator('#files').setInputFiles([{ name: 'hello.txt', mimeType: 'text/plain', buffer: Buffer.from('hello') }, { name: 'denied.txt', mimeType: 'text/plain', buffer: Buffer.from('bad') }]);
  await page.locator('input[name=permission][value=public]').check();
  await page.locator('#confirmModal').click();
  await page.locator('#modal').waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.querySelector('#tasks')?.textContent.includes('denied.txt'));
  await page.locator('#cdnTab').click();
  await page.locator('#domain').fill('https://cdn.example.com/assets/main.js');
  await page.locator('#searchMaps').click();
  await page.locator('#maps input[type=radio]').first().check();
  await page.locator('#paths').fill('/*');
  await page.locator('#invalidateButton').click();
  await page.locator('#wildcardConfirm').check();
  await page.locator('#confirmModal').click();
  await page.locator('#modal').waitFor({ state: 'hidden' });
  await page.waitForFunction(() => document.querySelector('#tasks')?.textContent.includes('operation-demo-map'));
  const jobs = (await (await page.request.get(origin + '/api/gcp/jobs')).json()).items;
  assert.equal(jobs.find(job => job.type === 'copy').state, 'partial');
  assert.equal(jobs.find(job => job.key === 'hello.txt').state, 'completed');
  assert.equal(jobs.find(job => job.key === 'denied.txt').state, 'failed');
  assert.equal(jobs.find(job => job.type === 'invalidation').state, 'completed');
  await page.locator('#tasks details.task-group').first().locator('summary').first().click();
  await page.getByRole('button', { name: '查看全部失败项', exact: true }).first().click();
  await checked('#failureDialog');
  assert.ok(await page.locator('#failureItems tr').count() >= 2);
  await page.getByRole('button', { name: '关闭失败详情', exact: true }).click();
  await mkdir(new URL('../.codex-tmp/', import.meta.url), { recursive: true });
  await page.screenshot({ path: fileURLToPath(new URL('../.codex-tmp/gcp-desktop.png', import.meta.url)), fullPage: true });
  await page.reload();
  await checked('#workspace');
  await page.waitForFunction(() => document.querySelector('#tasks')?.textContent.includes('operation-demo-map'));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#cdnTab').click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'mobile viewport must not overflow');
  await page.screenshot({ path: fileURLToPath(new URL('../.codex-tmp/gcp-mobile.png', import.meta.url)), fullPage: true });
  await page.goto(origin + '/');
  await checked('#connectForm');
  await page.locator('a[href="/gcp"]').click();
  await checked('#workspace');
  assert.deepEqual(errors, []);
  console.log('PASS: real Chrome GCP connection, project, pagination, folder, copy, permission choice, uploads, CDN, session restore, AWS link, desktop/mobile layout; simulated cloud only.');
} finally {
  await browser?.close();
  await new Promise(resolve => server.close(resolve));
}
